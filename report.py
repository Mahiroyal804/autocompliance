def build_report(company: str, result: dict, out_path: str) -> str:
    e = html.escape
    fwchips = "".join(
        f"<div><b>{s}%</b><br>{e(fw)}</div>" for fw, s in result["frameworks"].items()
    )
    fixes_html = ""
    for f in result["fixes"][:15]:
        fixes_html += (
            f'<div class="fix"><span class="p p{f["priority"]}">{f["priority"]}</span> '
            f'<span style="color:#8b93b8">[{e(f["control"])} · {e(f["framework"])}]</span><br>{e(f["fix"])}</div>'
        )
    if not fixes_html:
        fixes_html = '<div class="fix">✅ No gaps found. Maintain with quarterly reviews.</div>'

    controls_html = ""
    for c in result["controls"]:
        badge = {"pass": "bpass", "partial": "bpartial", "fail": "bfail"}[c["status"]]
        qs = ""
        for q in c["questions"]:
            mark = "✓" if q["answer"] == "y" else ("◐" if q["answer"] == "p" else "✗")
            cls = "py" if q["answer"] == "y" else ""
            qs += f'<div class="q"><b class="{cls}">{mark}</b> {e(q["q"])}</div>'
        controls_html += (
            f'<div class="ctrl {c["status"]}"><span class="t">{e(c["id"])} — {e(c["title"])}</span>'
            f'<span class="badge {badge}">{c["score"]}%</span>'
            f'<div class="m">{e(c["why"])}</div>{qs}</div>'
        )

    page = PAGE
    for k, val in {
        "{{company}}": e(company), "{{grade}}": result["grade"],
        "{{overall}}": str(result["overall"]),
        "{{date}}": time.strftime("%Y-%m-%d"),
        "{{fwchips}}": fwchips, "{{fixes}}": fixes_html, "{{controls}}": controls_html,
    }.items():
        page = page.replace(k, val)

    os.makedirs(os.path.dirname(os.path.abspath(out_path)), exist_ok=True)
    with open(out_path, "w") as f:
        f.write(page)
    return out_path
